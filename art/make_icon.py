#!/usr/bin/env python3
"""Launcher icon for Kanji Color Key: one original kanji-like glyph (5 strokes, the shape of 主 "master")
drawn as colored strokes on a dark background, in the app's palette.

Writes (from one stroke definition):
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive foreground (108 dp layer, vector)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed-icon layer (single color)
  art/icon-512.png, fastlane/.../images/icon.png         512 px (full-bleed square)
  <preview path> (argv[1], default art/icon-preview.png)  preview sheet
Usage: python3 art/make_icon.py [preview.png]
"""
import sys, math, os
from PIL import Image, ImageDraw, ImageFont

BG = (0x1B, 0x1E, 0x26)
# stroke color in stroke order: 黒 (drawn light on the dark background), 赤, 青, 緑, 黒
LIGHT, RED, BLUE, GREEN = '#F1EEE4', '#E03A3A', '#4A78F0', '#22A55A'
W = 7.2  # stroke width in the 108-unit layer
# cubic Béziers in the 108 x 108 adaptive layer (safe zone: circle r=33 around 54,54)
STROKES = [
    (LIGHT, [(50.5, 25.5), (53, 27), (55.5, 29), (57.5, 31.5)]),            # 1 dot
    (RED,   [(35, 41), (46, 40.2), (62, 39.4), (73.5, 39.2)]),              # 2 top bar
    (BLUE,  [(38, 57.5), (48, 56.8), (60, 56.3), (70.5, 56.2)]),            # 3 middle bar
    (GREEN, [(54, 41.5), (54.4, 53), (54.4, 64), (54, 75.5)]),              # 4 vertical
    (LIGHT, [(32.5, 76.5), (45, 75.6), (63, 75.1), (76, 75.4)]),            # 5 base
]

def d_attr(p):
    (a, b, c, d) = p
    return f"M{a[0]},{a[1]} C{b[0]},{b[1]} {c[0]},{c[1]} {d[0]},{d[1]}"

def vector(mono):
    paths = []
    for color, p in STROKES:
        col = '#FFFFFFFF' if mono else '#FF' + color[1:]
        paths.append(f'''    <path
        android:pathData="{d_attr(p)}"
        android:strokeColor="{col}"
        android:strokeWidth="{W}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />''')
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by art/make_icon.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n' + '\n'.join(paths) + '\n</vector>\n')

def bez(p, t):
    (a, b, c, d) = p; u = 1 - t
    return tuple(u*u*u*a[i] + 3*u*u*t*b[i] + 3*u*t*t*c[i] + t*t*t*d[i] for i in range(2))

def render(size, scale_layer=1.0, bg=True, mono=None, ss=4):
    """Render the 108-unit layer into size x size; scale_layer > 1 zooms (for the full-bleed 512 icon)."""
    S = size * ss
    im = Image.new('RGBA', (S, S), BG + (255,) if bg else (0, 0, 0, 0))
    dr = ImageDraw.Draw(im)
    k = S / 108 * scale_layer; off = S / 2 - 54 * k
    for color, p in STROKES:
        col = mono or color
        pts = [bez(p, i / 200) for i in range(201)]
        pts = [(off + x * k, off + y * k) for x, y in pts]
        r = W * k / 2
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            dr.line([(x0, y0), (x1, y1)], fill=col, width=int(round(2 * r)))
        for x, y in (pts[0], pts[-1]) + tuple(pts[::10]):
            dr.ellipse([x - r, y - r, x + r, y + r], fill=col)
    return im.resize((size, size), Image.LANCZOS)

def mask(im, kind):
    S = im.size[0]; m = Image.new('L', (S * 4, S * 4), 0); d = ImageDraw.Draw(m)
    if kind == 'circle': d.ellipse([0, 0, S * 4 - 1, S * 4 - 1], fill=255)
    else: d.rounded_rectangle([0, 0, S * 4 - 1, S * 4 - 1], radius=S * 4 * 0.22, fill=255)
    m = m.resize((S, S), Image.LANCZOS); out = Image.new('RGBA', (S, S), (0, 0, 0, 0)); out.paste(im, (0, 0), m); return out

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    res = os.path.join(root, 'app/src/main/res/drawable')
    open(os.path.join(res, 'ic_launcher_foreground.xml'), 'w').write(vector(False))
    open(os.path.join(res, 'ic_launcher_monochrome.xml'), 'w').write(vector(True))
    # 512 px store icon: the 72 dp visible part of the layer (zoom 108/72), full-bleed square
    big = render(512, scale_layer=108 / 80).convert('RGB')
    big.save(os.path.join(root, 'art/icon-512.png'), optimize=True)
    for loc in ('en-US', 'ja-JP'):
        d = os.path.join(root, f'fastlane/metadata/android/{loc}/images'); os.makedirs(d, exist_ok=True)
        big.save(os.path.join(d, 'icon.png'), optimize=True)
    # preview sheet
    prev = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'art/icon-preview.png')
    sheet = Image.new('RGB', (1280, 640), (236, 236, 232)); dk = Image.new('RGB', (640, 640), (24, 24, 28))
    sheet.paste(dk, (640, 0))
    lay = render(432, scale_layer=1.0)
    full = mask(render(432, scale_layer=108 / 72), 'circle')
    items = [(big.resize((256, 256), Image.LANCZOS).convert('RGBA'), (40, 40), '512 px store icon'),
             (mask(render(256, 108 / 72), 'circle'), (340, 40), 'adaptive · circle'),
             (mask(render(256, 108 / 72), 'squircle'), (40, 340), 'adaptive · rounded square'),
             (lay.resize((256, 256), Image.LANCZOS), (340, 340), '108 dp layer (safe zone)')]
    dr = ImageDraw.Draw(sheet)
    try: font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 18)
    except OSError: font = ImageFont.load_default()
    for im, (x, y), label in items:
        sheet.paste(im, (x, y), im); dr.text((x, y + 262), label, fill=(60, 60, 60), font=font)
    # safe-zone circle on the layer view
    dr.ellipse([340 + 128 - 128 * 66 / 108, 340 + 128 - 128 * 66 / 108, 340 + 128 + 128 * 66 / 108, 340 + 128 + 128 * 66 / 108], outline=(255, 200, 0), width=2)
    # dark side: launcher sizes + themed (monochrome) icon
    x = 680
    for s in (192, 96, 48):
        ic = mask(render(s, 108 / 72), 'circle'); sheet.paste(ic, (x, 60), ic); x += s + 30
    mono = mask(render(192, 108 / 72, bg=False, mono='#D8E2FF'), 'circle')
    tint = Image.new('RGBA', (192, 192), (0, 0, 0, 0)); bgc = mask(Image.new('RGBA', (192, 192), (0x2A, 0x33, 0x4D, 255)), 'circle')
    tint.paste(bgc, (0, 0), bgc); tint.alpha_composite(mono)
    sheet.paste(tint, (680, 340), tint)
    dr.text((680, 540), 'themed icon (monochrome layer)', fill=(220, 220, 220), font=font)
    dr.text((680, 270), 'launcher sizes 192 / 96 / 48 px', fill=(220, 220, 220), font=font)
    os.makedirs(os.path.dirname(prev), exist_ok=True); sheet.save(prev, optimize=True)
    big.save(os.path.join(root, 'docs/icon.png'), optimize=True) if os.path.isdir(os.path.join(root, 'docs')) else None
    print('ok', prev)

main()
