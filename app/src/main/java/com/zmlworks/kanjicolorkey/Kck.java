    /** KANA_GLYPH: a one-color tail kana (\u201c1色かな\u201d, 5 bit kana + 1 color). */
    public enum Type { KANJI, HEX, ALPHA, KANA, KANA_GLYPH }

    public static final class Token {
        public final Type type;
        public final String ch;
        public final int index;      // kanji pool index / kana index (else -1)
        public final int[] colors;   // kanji/kana: one per stroke; hex/alpha/one-color kana: a single color
        Token(Type type, String ch, int index, int[] colors) { this.type = type; this.ch = ch; this.index = index; this.colors = colors; }
        public int color() { return colors[0]; }
        static Token kanji(Pool p, int idx, int[] colors) { return new Token(Type.KANJI, p.chars[idx], idx, colors); }
        static Token hex(char c, int color) { return new Token(Type.HEX, String.valueOf(c), -1, new int[]{color}); }
        static Token alpha(int v7) { return new Token(Type.ALPHA, String.valueOf(ALPHA.charAt(v7 >> 2)), -1, new int[]{v7 & 3}); }
        static Token alpha(int glyph, int color) { return new Token(Type.ALPHA, String.valueOf(ALPHA.charAt(glyph)), -1, new int[]{color}); }
        static Token kana(KanaSet k, int idx, int[] colors) { return new Token(Type.KANA, k.chars[idx], idx, colors); }
        static Token kanaGlyph(KanaSet k, int idx, int color) { return new Token(Type.KANA_GLYPH, k.chars[idx], idx, new int[]{color}); }
    }

    public static final class Encoded {
        public final List<Token> tokens; public final String text;
        public final int totalBits, dataBits, writtenBits, surplus; public final long checkBits;
        public final boolean fixed; // KF (fixed-length kana)
        Encoded(List<Token> tokens, String text, int totalBits, int dataBits, long checkBits, int writtenBits) {
            this(tokens, text, totalBits, dataBits, checkBits, writtenBits, false);
        }
        Encoded(List<Token> tokens, String text, int totalBits, int dataBits, long checkBits, int writtenBits, boolean fixed) {
            this.tokens = tokens; this.text = text; this.totalBits = totalBits; this.dataBits = dataBits;
            this.checkBits = checkBits; this.writtenBits = writtenBits; this.surplus = writtenBits - totalBits; this.fixed = fixed;
        }
        public int count(Type t) { int n = 0; for (Token k : tokens) if (k.type == t) n++; return n; }
    }

    private static String header(String prefix, long dataLen, long checkBits) {
        return prefix + "(" + dataLen + (checkBits != 0 ? "+" + checkBits : "") + "bit)";
    }

    // ---------- encode ----------
    public static Encoded encodeBits(Pool pool, byte[] dataBits, long checkBits) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        int pos = 0;
        while (s.L - pos >= 12) {
            int idx = readInt(s.bits, pos, 12); pos += 12;
            int[] colors = new int[pool.counts[idx]];
            for (int k = 0; k < colors.length; k++) { colors[k] = readInt(s.bits, pos, 2); pos += 2; }
            tokens.add(Token.kanji(pool, idx, colors));
        }
        while (pos < s.L) {
            tokens.add(Token.hex(HEX.charAt(readInt(s.bits, pos, 4)), readInt(s.bits, pos + 4, 2))); pos += 6;
        }
        return new Encoded(tokens, formatTokens(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, pos);
    }

    public static Encoded encodeHex(Pool pool, String hex, long checkBits) { return encodeBits(pool, hexToBits(hex), checkBits); }

    public static String formatTokens(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("", dataLen, checkBits));
        for (Token t : tokens) { sb.append(t.ch); for (int c : t.colors) sb.append(c); }
        return sb.toString();
    }

    public static Encoded encodeAlpha(byte[] dataBits, long checkBits) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        for (int pos = 0; pos < s.L; pos += 7) tokens.add(Token.alpha(readInt(s.bits, pos, 5), readInt(s.bits, pos + 5, 2)));
        return new Encoded(tokens, formatAlpha(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, tokens.size() * 7);
    }

    public static String formatAlpha(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("A", dataLen, checkBits));
        for (int i = 0; i < tokens.size(); i++) {
            if (i != 0 && i % 4 == 0) sb.append(' ');
            sb.append(tokens.get(i).ch).append(tokens.get(i).color());
        }
        return sb.toString();
    }

    /** Ending of mixed mode: KANJI keeps the chosen types to the end (the last symbol is padded with surplus bits);
     * ALPHA / KANA finish with alpha glyphs / one-color kana as soon as the next kanji or kana would not be fully used. */
    public enum Tail { KANJI, ALPHA, KANA }

    /** Mixed mode (v1.1 signature). alphaPos: 1-based positions that are alpha glyphs. tailAlpha: finish with glyphs. */
    public static Encoded encodeMixed(Pool pool, byte[] dataBits, long checkBits, Set<Integer> alphaPos, boolean tailAlpha) {
        return encodeMixed(pool, dataBits, checkBits, alphaPos, Collections.<Integer>emptySet(), tailAlpha ? Tail.ALPHA : Tail.KANJI, null);
    }

    /** Mixed mode (v1.2): alphaPos / kanaPos are 1-based positions of alpha glyphs / kana, the rest are kanji. */
    public static Encoded encodeMixed(Pool pool, byte[] dataBits, long checkBits, Set<Integer> alphaPos, Set<Integer> kanaPos, Tail tail, KanaSet kana) {
        if (!kanaPos.isEmpty() || tail == Tail.KANA) needKana(kana);
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        int pos = 0;
        Type rest = null;
        for (int i = 1; pos < s.L; i++) {
            Type type = rest != null ? rest : alphaPos.contains(i) ? Type.ALPHA : kanaPos.contains(i) ? Type.KANA : Type.KANJI;
            if (rest == null && tail != Tail.KANJI && type != Type.ALPHA) {
                int full = type == Type.KANJI ? 12 + 2 * pool.counts[readInt(s.bits, pos, 12)] : 5 + 2 * kana.counts[readInt(s.bits, pos, 5)];
                if (s.L - pos < full) type = rest = tail == Tail.ALPHA ? Type.ALPHA : Type.KANA_GLYPH;
            }
            if (type == Type.ALPHA) { tokens.add(Token.alpha(readInt(s.bits, pos, 5), readInt(s.bits, pos + 5, 2))); pos += 7; }
            else if (type == Type.KANA_GLYPH) { tokens.add(Token.kanaGlyph(kana, readInt(s.bits, pos, 5), readInt(s.bits, pos + 5, 2))); pos += 7; }
            else {
                boolean kanji = type == Type.KANJI;
                int n = kanji ? 12 : 5, idx = readInt(s.bits, pos, n); pos += n;
                int[] colors = new int[kanji ? pool.counts[idx] : kana.counts[idx]];
                for (int k = 0; k < colors.length; k++) { colors[k] = readInt(s.bits, pos, 2); pos += 2; }
                tokens.add(kanji ? Token.kanji(pool, idx, colors) : Token.kana(kana, idx, colors));
            }
        }
        return new Encoded(tokens, formatMixed(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, pos);
    }

    public static String formatMixed(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("M", dataLen, checkBits));
        for (int i = 0; i < tokens.size(); i++) {
            if (i != 0) sb.append(' ');
            Token t = tokens.get(i);
            sb.append(t.ch);
            for (int c : t.colors) sb.append(c);
        }
        return sb.toString();
    }

    // ---------- fixed-length kana (v1.2), header "KF(256+12bit)" ----------
    /** Every kana carries exactly 3 colored strokes (5 + 6 = 11 bit); the 4th stroke of a 4-stroke kana is black. */
    public static Encoded encodeKanaFixed(KanaSet kana, byte[] dataBits, long checkBits) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        int pos = 0;
        for (; pos < s.L; pos += 11) {
            int idx = readInt(s.bits, pos, 5);
            int[] colors = new int[Math.max(3, kana.counts[idx])];
            for (int j = 0; j < 3; j++) colors[j] = readInt(s.bits, pos + 5 + 2 * j, 2);
            tokens.add(Token.kana(kana, idx, colors));
        }
        return new Encoded(tokens, formatKanaFixed(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, pos, true);
    }

    public static String formatKanaFixed(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("KF", dataLen, checkBits));
        for (int i = 0; i < tokens.size(); i++) {
            if (i != 0) sb.append(' ');
            sb.append(tokens.get(i).ch);
            for (int c : tokens.get(i).colors) sb.append(c);
        }
        return sb.toString();
    }

    // ---------- uncertain color sequences ----------
    /** Raw expansions above this are refused (the JS would try and run out of time/memory). */
    static final double EXPAND_LIMIT = 8_000_000;

    public static List<int[]> expandColorSpec(String spec) {
        List<Integer> syms = new ArrayList<>(); // 0..3 or -1 for '?'
        List<int[]> groups = new ArrayList<>(); // {kind '(' or '[', start, len}
        int[] open = null;
        for (int k = 0; k < spec.length(); k++) {
            char ch = spec.charAt(k);
            if (ch == '(' || ch == '[') {
                if (open != null) throw new KckException("nested brackets");
                open = new int[]{ch, syms.size(), 0};
            } else if (ch == ')' || ch == ']') {
                if (open == null || (open[0] == '(') != (ch == ')')) throw new KckException("mismatched bracket");
                open[2] = syms.size() - open[1]; groups.add(open); open = null;
            } else if (ch == '?') syms.add(-1);
            else if (ch >= '0' && ch <= '3') syms.add(ch - '0');
            else throw new KckException("bad color char " + new String(Character.toChars(spec.codePointAt(k))));
        }
        if (open != null) throw new KckException("unclosed bracket");
        // guard against expansions the phone cannot hold (see EXPAND_LIMIT)
        double raw = 1;
        int restLen = syms.size();
        for (int[] g : groups) if (g[0] == '[') for (int i = 2; i <= g[2]; i++) raw *= i;
        for (int[] g : groups) if (g[0] == '(') raw *= (syms.size() - g[2] + 1);
        for (int v : syms) if (v < 0) raw *= 4;
        if (raw > EXPAND_LIMIT) throw new KckException("too many combinations (" + jsNumber(raw) + "+); narrow the uncertainty");
        List<int[]> variants = new ArrayList<>();
        int[] ids0 = new int[restLen];
        for (int i = 0; i < restLen; i++) ids0[i] = i;
        variants.add(ids0);
        for (int[] g : groups) {
            if (g[0] != '[') continue;
            List<int[]> next = new ArrayList<>();
            for (int[] v : variants) for (int[] p : permutations(Arrays.copyOfRange(v, g[1], g[1] + g[2]))) {
                int[] w = v.clone();
                System.arraycopy(p, 0, w, g[1], p.length);
                next.add(w);
            }
            variants = next;
        }
        for (int[] g : groups) {
            if (g[0] != '(') continue;
            boolean[] in = new boolean[syms.size()];
            for (int i = g[1]; i < g[1] + g[2]; i++) in[i] = true;
            List<int[]> next = new ArrayList<>();
            for (int[] v : variants) {
                int[] block = Arrays.stream(v).filter(x -> in[x]).toArray(), rest = Arrays.stream(v).filter(x -> !in[x]).toArray();
                for (int p = 0; p <= rest.length; p++) {
                    int[] w = new int[v.length];
                    System.arraycopy(rest, 0, w, 0, p);
                    System.arraycopy(block, 0, w, p, block.length);
                    System.arraycopy(rest, p, w, p + block.length, rest.length - p);
                    next.add(w);
                }
            }
            variants = next;
        }
        LinkedHashMap<String, int[]> out = new LinkedHashMap<>();
        for (int[] v : variants) {
            List<int[]> partial = new ArrayList<>();
            partial.add(new int[0]);
            for (int id : v) {
                int s = syms.get(id);
                List<int[]> np = new ArrayList<>();
                for (int[] a : partial) {
                    if (s < 0) for (int c = 0; c < 4; c++) np.add(append(a, c));
                    else np.add(append(a, s));
                }
                partial = np;
            }
            for (int[] a : partial) {
                StringBuilder key = new StringBuilder();
                for (int c : a) key.append(c);
                out.putIfAbsent(key.toString(), a);
            }
        }
        return new ArrayList<>(out.values());
    }

    private static int[] append(int[] a, int c) { int[] r = Arrays.copyOf(a, a.length + 1); r[a.length] = c; return r; }

    static List<int[]> permutations(int[] a) {
        List<int[]> res = new ArrayList<>();
        if (a.length <= 1) { res.add(a); return res; }
        for (int i = 0; i < a.length; i++) {
            int[] rest = new int[a.length - 1];
            System.arraycopy(a, 0, rest, 0, i);
            System.arraycopy(a, i + 1, rest, i, a.length - i - 1);
            for (int[] p : permutations(rest)) {
                int[] w = new int[a.length];
                w[0] = a[i];
                System.arraycopy(p, 0, w, 1, p.length);
                res.add(w);
            }
        }
        return res;
    }

    // ---------- parse ----------
    /** Parsed symbol: type, char, pool index (kanji), the written spec and the candidate option values. */
    public static final class PToken {
        public final Type type; public final String ch; public final int index; public final String spec;
        final List<int[]> colorOptions; // kanji/hex/kana: color arrays
        final int[] valueOptions;       // alpha: 7-bit values
        final boolean glyphAlt;         // a last full kana written in one color: also try it as a one-color kana
        PToken(Type type, String ch, int index, String spec, List<int[]> colorOptions, int[] valueOptions) {
            this(type, ch, index, spec, colorOptions, valueOptions, false);
        }
        PToken(Type type, String ch, int index, String spec, List<int[]> colorOptions, int[] valueOptions, boolean glyphAlt) {
            this.type = type; this.ch = ch; this.index = index; this.spec = spec; this.colorOptions = colorOptions; this.valueOptions = valueOptions;
            this.glyphAlt = glyphAlt;
        }
        public int optionCount() { return valueOptions != null ? valueOptions.length : colorOptions.size(); }
    }

    public static final class Parsed {
        public final long dataBits, checkBits; public final List<PToken> tokens; public final boolean fixed;
        Parsed(long dataBits, long checkBits, List<PToken> tokens) { this(dataBits, checkBits, tokens, false); }
        Parsed(long dataBits, long checkBits, List<PToken> tokens, boolean fixed) { this.dataBits = dataBits; this.checkBits = checkBits; this.tokens = tokens; this.fixed = fixed; }
    }

    private static final Pattern H_TEXT = Pattern.compile("^[(（]([0-9]+)(?:\\+([0-9]+))?bit[)）]", Pattern.CASE_INSENSITIVE);
    private static final Pattern H_MIXED = Pattern.compile("^[MmKk][(（]([0-9]+)(?:\\+([0-9]+))?bit[)）]", Pattern.CASE_INSENSITIVE);
    private static final Pattern H_KF = Pattern.compile("^[Kk][Ff][(（]([0-9]+)(?:\\+([0-9]+))?bit[)）]", Pattern.CASE_INSENSITIVE);
    private static final Pattern HALFWIDTH = Pattern.compile("[\\uFF61-\\uFF9F]+");
    private static final Pattern PLAIN = Pattern.compile("^([0-3])\\1*$");

    /** Whitespace removed; halfwidth katakana (ｳ) read as fullwidth (NFKC on that range only); then NFC. */
    static String squeeze(String text) {
        String t = WS_RUN.matcher(text).replaceAll("");
        Matcher m = HALFWIDTH.matcher(t);
        StringBuilder sb = new StringBuilder();
        int last = 0;
        while (m.find()) { sb.append(t, last, m.start()).append(Normalizer.normalize(m.group(), Normalizer.Form.NFKC)); last = m.end(); }
        sb.append(t.substring(last));
        return Normalizer.normalize(sb.toString(), Normalizer.Form.NFC);
    }
    private static final Pattern H_ALPHA = Pattern.compile("^A[(（]([0-9]+)(?:\\+([0-9]+))?BIT[)）]");

    /** JS unary + on a digit string (doubles); clamped to long, which only matters for absurd headers. */
    private static long num(String s) {
        double d = Double.parseDouble(s);
        return d >= 9e15 ? (long) 9e15 : (long) d;
    }

    private static String cp(int c) { return new String(Character.toChars(c)); }

    private static String joinCps(int[] cps, int from) {
        StringBuilder sb = new StringBuilder();
        for (int i = from; i < cps.length; i++) sb.appendCodePoint(cps[i]);
        return sb.toString();
    }

    private static boolean isColorDigitOrQ(int d) { return (d >= '0' && d <= '3') || d == '?'; }

    /**
     * The color run after a kanji or hex digit (shared by parseText and parseMixed). Returns {spec, newI} via the
     * holder; throws if the count does not match.
     */
    private static String colorRun(int[] chars, int[] iRef, int need, String c) {
        int[] nRef = {0};
        String spec = colorRun(chars, iRef, need, nRef);
        if (nRef[0] != need) throw new KckException("\"" + c + "\" needs " + need + " colors, got " + nRef[0]);
        return spec;
    }

    /** colorRun without the count check: the number of colors read is returned in nRef[0]. */
    private static String colorRun(int[] chars, int[] iRef, int need, int[] nRef) {
        int i = iRef[0], n = 0;
        StringBuilder spec = new StringBuilder();
        while (i < chars.length) {
            if (n < need) { String cn = colorName(chars[i]); if (cn != null) chars[i] = cn.charAt(0); }
            int d = chars[i];
            if (n == need && d != ')' && d != ']') break;
            if (isColorDigitOrQ(d)) n++;
            else if (d != '(' && d != ')' && d != '[' && d != ']') break;
            spec.appendCodePoint(d); i++;
        }
        iRef[0] = i;
        nRef[0] = n;
        return spec.toString();
    }

    public static Parsed parseText(Pool pool, String text) {
        String t = Normalizer.normalize(WS_RUN.matcher(text).replaceAll(""), Normalizer.Form.NFC);
        Matcher m = H_TEXT.matcher(t);
        if (!m.find()) throw new KckException("missing header like (256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        int[] chars = t.substring(m.end()).codePoints().toArray();
        List<PToken> tokens = new ArrayList<>();
        int[] iRef = {0};
        long budget = dataBits + checkBits;
        while (iRef[0] < chars.length) {
            String c = cp(chars[iRef[0]++]);
            int need;
            Type type; int index = -1; String ch;
            if (budget >= 12) {
                Integer idx = pool.indexOf(c);
                if (idx == null) throw new KckException("\"" + c + "\" is not in the kanji pool");
                index = idx; need = pool.counts[idx]; type = Type.KANJI; ch = c;
                budget -= 12 + 2L * need;
            } else {
                String lc = c.toLowerCase(Locale.ROOT);
                if (!HEX.contains(lc)) throw new KckException("expected hex char, got \"" + c + "\"");
                need = 1; type = Type.HEX; ch = lc; budget -= 6;
            }
            String spec = colorRun(chars, iRef, need, c);
            tokens.add(new PToken(type, ch, index, spec, expandColorSpec(spec), null));
            if (budget <= 0) break;
        }
        if (budget > 0) throw new KckException("text too short for header");
        if (iRef[0] < chars.length) throw new KckException("trailing characters: " + joinCps(chars, iRef[0]));
        return new Parsed(dataBits, checkBits, tokens);
    }

    public static Parsed parseAlpha(String text) {
        StringBuilder sb = new StringBuilder();
        String w = WS_RUN.matcher(text).replaceAll("");
        for (int k = 0; k < w.length(); k++) {
            char ch = w.charAt(k);
            String cn = colorName(ch);
            sb.append(cn != null ? cn : String.valueOf(ch));
        }
        String t = sb.toString().toUpperCase(Locale.ROOT);
        Matcher m = H_ALPHA.matcher(t);
        if (!m.find()) throw new KckException("missing header like A(256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        String body = t.substring(m.end());
        long n = (dataBits + checkBits + 6) / 7;
        if (dataBits + checkBits <= 0) n = 0;
        if (body.length() != 2 * n) throw new KckException("expected " + n + " symbols (" + 2 * n + " chars), got " + body.length() + " chars");
        List<PToken> tokens = new ArrayList<>();
        for (int i = 0; i < n; i++) {
            char g = body.charAt(2 * i), c = body.charAt(2 * i + 1);
            if (g != '?' && ALPHA.indexOf(g) < 0) throw new KckException("\"" + g + "\" is not in the alpha set (0, 1, 8, U are excluded)");
            if (!isColorDigitOrQ(c)) throw new KckException("bad color \"" + c + "\" after \"" + g + "\"");
            tokens.add(new PToken(Type.ALPHA, String.valueOf(g), -1, String.valueOf(c), null, alphaOptions(g, c)));
        }
        return new Parsed(dataBits, checkBits, tokens);
    }

    private static int[] alphaOptions(int g, int c) {
        int[] gs, cs;
        if (g == '?') { gs = new int[32]; for (int a = 0; a < 32; a++) gs[a] = a; } else gs = new int[]{ALPHA.indexOf(g)};
        if (c == '?') cs = new int[]{0, 1, 2, 3}; else cs = new int[]{c - '0'};
        int[] o = new int[gs.length * cs.length];
        int k = 0;
        for (int a : gs) for (int b : cs) o[k++] = a * 4 + b;
        return o;
    }

    private static boolean isAlnumQ(int c) {
        return (c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '?';
    }

    public static Parsed parseMixed(Pool pool, String text) { return parseMixed(pool, text, null); }

    public static Parsed parseMixed(Pool pool, String text, KanaSet kana) {
        String t = squeeze(text);
        Matcher m = H_MIXED.matcher(t);
        if (!m.find()) throw new KckException("missing header like M(256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        int[] chars = t.substring(m.end()).codePoints().toArray();
        List<PToken> tokens = new ArrayList<>();
        int[] iRef = {0};
        long budget = dataBits + checkBits;
        boolean glyphRun = false;
        while (iRef[0] < chars.length && budget > 0) {
            int c = chars[iRef[0]++];
            String cs = cp(c);
            if (isAlnumQ(c)) {
                char g = Character.toUpperCase((char) c);
                String col = null;
                if (iRef[0] < chars.length) { String cn = colorName(chars[iRef[0]]); col = cn != null ? cn : cp(chars[iRef[0]]); }
                iRef[0]++;
                if (g != '?' && ALPHA.indexOf(g) < 0) throw new KckException("\"" + g + "\" is not in the alpha set (0, 1, 8, U are excluded)");
                if (col == null || !containsColorChar(col)) throw new KckException("bad color \"" + (col == null ? "" : col) + "\" after \"" + g + "\"");
                if (glyphRun) throw onlyGlyphs(String.valueOf(g));
                tokens.add(new PToken(Type.ALPHA, String.valueOf(g), -1, col, null, alphaOptions(g, col.charAt(0))));
                budget -= 7;
            } else if (kana != null && kana.indexOf(cs) != null) {
                int index = kana.indexOf(cs), st = kana.counts[index];
                int[] nRef = {0};
                String spec = colorRun(chars, iRef, st, nRef);
                boolean plain = PLAIN.matcher(spec).find();
                if (nRef[0] == 1) {
                    glyphRun = true;
                    tokens.add(new PToken(Type.KANA_GLYPH, cs, index, spec, expandColorSpec(spec), null)); budget -= 7;
                } else if (nRef[0] == st && glyphRun) {
                    // a one-color kana copied stroke by stroke ("ウ222" for "ウ2")
                    if (!plain) throw new KckException("\"" + cs + "\" after a one-color kana must also be one color, got " + spec);
                    List<int[]> one = new ArrayList<>(); one.add(new int[]{spec.charAt(0) - '0'});
                    tokens.add(new PToken(Type.KANA_GLYPH, cs, index, spec.substring(0, 1), one, null)); budget -= 7;
                } else if (nRef[0] == st) {
                    // the last symbol may also be a one-color kana copied stroke by stroke: try both readings
                    tokens.add(new PToken(Type.KANA, cs, index, spec, expandColorSpec(spec), null, budget <= 7 && plain)); budget -= 5 + 2L * st;
                } else throw new KckException("\"" + cs + "\" needs " + st + " colors (or 1 as a one-color tail kana), got " + nRef[0]);
            } else {
                Integer idx = pool.indexOf(cs);
                if (idx == null) throw new KckException("\"" + cs + "\" is not in the kanji pool");
                if (glyphRun) throw onlyGlyphs(cs);
                int need = pool.counts[idx];
                String spec = colorRun(chars, iRef, need, cs);
                tokens.add(new PToken(Type.KANJI, cs, idx, spec, expandColorSpec(spec), null));
                budget -= 12 + 2L * need;
            }
        }
        if (budget > 0) throw new KckException("text too short for header");
        if (iRef[0] < chars.length) throw new KckException("trailing characters: " + joinCps(chars, iRef[0]));
        return new Parsed(dataBits, checkBits, tokens);
    }

    private static KckException onlyGlyphs(String c) {
        return new KckException("\"" + c + "\" cannot follow a one-color kana (only one-color kana until the end)");
    }

    public static Parsed parseKanaFixed(KanaSet kana, String text) {
        String t = squeeze(text);
        Matcher m = H_KF.matcher(t);
        if (!m.find()) throw new KckException("missing header like KF(256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        int[] chars = t.substring(m.end()).codePoints().toArray();
        List<PToken> tokens = new ArrayList<>();
        int[] iRef = {0};
        long budget = dataBits + checkBits;
        while (iRef[0] < chars.length && budget > 0) {
            String cs = cp(chars[iRef[0]++]);
            Integer index = kana.indexOf(cs);
            if (index == null) throw new KckException("\"" + cs + "\" is not in the kana set (" + String.join("", kana.chars) + ")");
            int st = kana.counts[index];
            int[] nRef = {0};
            String spec = colorRun(chars, iRef, st, nRef);
            if (nRef[0] != st) throw new KckException("\"" + cs + "\" needs " + st + " colors, got " + nRef[0]);
            LinkedHashMap<String, int[]> opts = new LinkedHashMap<>(); // the first 3 colors, distinct, in order
            for (int[] a : expandColorSpec(spec)) {
                int[] f = Arrays.copyOf(a, 3);
                opts.putIfAbsent("" + f[0] + f[1] + f[2], f);
            }
            tokens.add(new PToken(Type.KANA, cs, index, spec, new ArrayList<>(opts.values()), null));
            budget -= 11;
        }
        if (budget > 0) throw new KckException("text too short for header");
        if (iRef[0] < chars.length) throw new KckException("trailing characters: " + joinCps(chars, iRef[0]));
        return new Parsed(dataBits, checkBits, tokens, true);
    }

    private static boolean containsColorChar(String s) {
        for (int k = 0; k < s.length(); k++) if (isColorDigitOrQ(s.charAt(k))) return true;
        return false;
    }

