    public static final class KanaSet {
        public final String[] chars;
        public final int[] counts;
        final Map<String, Integer> index = new HashMap<>();

        public KanaSet(String kana, int[] counts) {
            int[] cps = kana.codePoints().toArray();
            if (cps.length != 32 || counts.length != 32 || Arrays.stream(cps).distinct().count() != 32) throw new KckException("kana set must have 32 distinct kana");
            chars = new String[32];
            for (int i = 0; i < 32; i++) { chars[i] = cp(cps[i]); index.put(chars[i], i); }
            this.counts = counts.clone();
        }

        public Integer indexOf(String c) { return index.get(c); }
    }

