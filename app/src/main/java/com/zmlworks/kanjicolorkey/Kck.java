    // ---------- SHA-256 ----------
    public static byte[] sha256(byte[] msg) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(msg);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    // ---------- bit helpers ----------
    public static byte[] hexToBits(String hex) {
        hex = hex.replaceFirst("^0[xX]", "");
        hex = WS_RUN.matcher(hex).replaceAll("").toLowerCase(Locale.ROOT);
        if (!hex.matches("[0-9a-f]*")) throw new KckException("invalid hex");
        byte[] bits = new byte[hex.length() * 4];
        for (int k = 0; k < hex.length(); k++) {
            int v = HEX.indexOf(hex.charAt(k));
            for (int i = 3; i >= 0; i--) bits[k * 4 + 3 - i] = (byte) ((v >> i) & 1);
        }
        return bits;
    }

    public static String bitsToHex(byte[] bits) {
        StringBuilder s = new StringBuilder();
        for (int i = 0; i < bits.length; i += 4) {
            int v = 0;
            for (int j = 0; j < 4; j++) v = v * 2 + (i + j < bits.length ? bits[i + j] : 0);
            s.append(HEX.charAt(v));
        }
        return s.toString();
    }

    public static byte[] bytesToBits(byte[] bytes) {
        byte[] b = new byte[bytes.length * 8];
        for (int k = 0; k < bytes.length; k++) for (int i = 7; i >= 0; i--) b[k * 8 + 7 - i] = (byte) ((bytes[k] >> i) & 1);
        return b;
    }

    public static byte[] bitsToBytes(byte[] bits) {
        byte[] out = new byte[(bits.length + 7) / 8];
        for (int i = 0; i < bits.length; i++) if (bits[i] != 0) out[i >> 3] |= (byte) (0x80 >> (i & 7));
        return out;
    }

    public static byte[] parseBitString(String s) {
        s = s.replaceAll("[" + JS_WS.substring(1, JS_WS.length() - 1) + "_]", "");
        if (!s.matches("[01]*")) throw new KckException("invalid bit string");
        byte[] b = new byte[s.length()];
        for (int i = 0; i < b.length; i++) b[i] = (byte) (s.charAt(i) - '0');
        return b;
    }

    static int readInt(byte[] bits, int pos, int n) {
        int v = 0;
        for (int i = 0; i < n; i++) v = v * 2 + (pos + i < bits.length ? bits[pos + i] : 0);
        return v;
    }

    static byte[] concat(byte[] a, byte[] b) {
        byte[] r = Arrays.copyOf(a, a.length + b.length);
        System.arraycopy(b, 0, r, a.length, b.length);
        return r;
    }

    private static void putU32(byte[] m, int off, long v) {
        m[off] = (byte) (v >>> 24); m[off + 1] = (byte) (v >>> 16); m[off + 2] = (byte) (v >>> 8); m[off + 3] = (byte) v;
    }

    /** Check code: first checkBits bits of SHA-256("kck1" || u32 bit length || data bytes) (at most 256). */
    public static byte[] checkCode(byte[] dataBits, long checkBits) {
        if (checkBits == 0) return new byte[0];
        byte[] body = bitsToBytes(dataBits), msg = new byte[8 + body.length];
        msg[0] = 0x6b; msg[1] = 0x63; msg[2] = 0x6b; msg[3] = 0x31;
        putU32(msg, 4, dataBits.length);
        System.arraycopy(body, 0, msg, 8, body.length);
        byte[] h = bytesToBits(sha256(msg));
        // JS: .slice(0, checkBits); a negative count drops bits from the end (unreachable from the UI, kept for parity)
        long end = checkBits < 0 ? Math.max(0, h.length + checkBits) : Math.min(h.length, checkBits);
        return Arrays.copyOf(h, (int) end);
    }

    private static byte[] surplusMsg(byte[] data) {
        byte[] body = bitsToBytes(data), msg = new byte[12 + body.length];
        msg[0] = 0x6b; msg[1] = 0x63; msg[2] = 0x6b; msg[3] = 0x70;
        putU32(msg, 4, data.length);
        System.arraycopy(body, 0, msg, 12, body.length);
        return msg;
    }

    /** Surplus bits (v1.1+): SHA-256("kckp" || u32 bit length || u32 counter || data) blocks, counter 0, 1, ... */
    public static byte[] surplusBits(byte[] dataBits, int n) {
        byte[] msg = surplusMsg(dataBits), out = new byte[n];
        int got = 0;
        for (int ctr = 0; got < n; ctr++) {
            putU32(msg, 8, ctr);
            byte[] h = bytesToBits(sha256(msg));
            int k = Math.min(h.length, n - got);
            System.arraycopy(h, 0, out, got, k);
            got += k;
        }
        return out;
    }

    /** "none", "zero" (v1.0 style), "surplus" (v1.1+) or null (reject). */
    public static String paddingKind(byte[] data, byte[] pad, int padFrom) { return paddingKind(data, pad, padFrom, pad.length); }

    /** paddingKind of pad[padFrom, padEnd). */
    public static String paddingKind(byte[] data, byte[] pad, int padFrom, int padEnd) {
        int n = padEnd - padFrom;
        if (n <= 0) return "none";
        boolean zero = true;
        for (int i = padFrom; i < padEnd; i++) if (pad[i] != 0) { zero = false; break; }
        if (zero) return "zero";
        byte[] msg = surplusMsg(data), h = null;
        for (int j = 0; j < n; j++) {
            if (j % 256 == 0) { putU32(msg, 8, j / 256); h = sha256(msg); }
            if (((h[(j % 256) >> 3] >> (7 - (j & 7))) & 1) != pad[padFrom + j]) return null;
        }
        return "surplus";
    }

    public static String paddingKind(byte[] data, byte[] pad) { return paddingKind(data, pad, 0); }

    private static final class Stream {
        final byte[] bits; final int L;
        Stream(byte[] bits, int L) { this.bits = bits; this.L = L; }
    }

    private static Stream streamOf(byte[] dataBits, long checkBits) {
        byte[] body = concat(dataBits, checkCode(dataBits, checkBits));
        return new Stream(concat(body, surplusBits(dataBits, SURPLUS_MAX)), body.length);
    }

    // ---------- pool ----------
    public static final class Pool {
        public final String[] chars;
        public final int[] counts;
        final Map<String, Integer> index = new HashMap<>();

        public Pool(String kanji, int[] counts) {
            int[] cps = kanji.codePoints().toArray();
            if (cps.length != 4096 || counts.length != 4096) throw new KckException("pool must have 4096 kanji");
            chars = new String[4096];
            for (int i = 0; i < 4096; i++) { chars[i] = new String(Character.toChars(cps[i])); index.put(chars[i], i); }
            this.counts = counts.clone();
        }

        public Integer indexOf(String c) { return index.get(c); }
    }

