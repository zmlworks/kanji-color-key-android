    static final String HEX = "0123456789abcdef";
    private static final int SURPLUS_MAX = 512;
    /** JavaScript's \s (ES2015+): ASCII whitespace plus the Unicode space separators, incl. U+3000. */
    static final String JS_WS = "[\\t\\n\\u000B\\f\\r \\u00A0\\u1680\\u2000-\\u200A\\u2028\\u2029\\u202F\\u205F\\u3000\\uFEFF]";
    private static final Pattern WS_RUN = Pattern.compile(JS_WS + "+");

    /** Error with the same message the JS core throws (shown to the user as-is, like the web app). */
    public static final class KckException extends IllegalArgumentException {
        public KckException(String m) { super(m); }
    }

    private static String colorName(int cp) {
        switch (cp) {
            case '黒': return "0";
            case '赤': return "1";
            case '青': return "2";
            case '緑': return "3";
            default: return null;
        }
    }

    // ---------- SHA-256 ----------
    public static byte[] sha256(byte[] msg) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(msg);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    // ---------- bit helpers ----------
    public static byte[] hexToBits(String hex) {
        hex = hex.replaceFirst("^0[xX]", "");
        hex = WS_RUN.matcher(hex).replaceAll("").toLowerCase(Locale.ROOT);
        if (!hex.matches("[0-9a-f]*")) throw new KckException("invalid hex");
        byte[] bits = new byte[hex.length() * 4];
        for (int k = 0; k < hex.length(); k++) {
            int v = HEX.indexOf(hex.charAt(k));
            for (int i = 3; i >= 0; i--) bits[k * 4 + 3 - i] = (byte) ((v >> i) & 1);
        }
        return bits;
    }

    public static String bitsToHex(byte[] bits) {
        StringBuilder s = new StringBuilder();
        for (int i = 0; i < bits.length; i += 4) {
            int v = 0;
            for (int j = 0; j < 4; j++) v = v * 2 + (i + j < bits.length ? bits[i + j] : 0);
            s.append(HEX.charAt(v));
        }
        return s.toString();
    }

    public static byte[] bytesToBits(byte[] bytes) {
        byte[] b = new byte[bytes.length * 8];
        for (int k = 0; k < bytes.length; k++) for (int i = 7; i >= 0; i--) b[k * 8 + 7 - i] = (byte) ((bytes[k] >> i) & 1);
        return b;
    }

    public static byte[] bitsToBytes(byte[] bits) {
        byte[] out = new byte[(bits.length + 7) / 8];
        for (int i = 0; i < bits.length; i++) if (bits[i] != 0) out[i >> 3] |= (byte) (0x80 >> (i & 7));
        return out;
    }

    public static byte[] parseBitString(String s) {
        s = s.replaceAll("[" + JS_WS.substring(1, JS_WS.length() - 1) + "_]", "");
        if (!s.matches("[01]*")) throw new KckException("invalid bit string");
        byte[] b = new byte[s.length()];
        for (int i = 0; i < b.length; i++) b[i] = (byte) (s.charAt(i) - '0');
        return b;
    }

    static int readInt(byte[] bits, int pos, int n) {
        int v = 0;
        for (int i = 0; i < n; i++) v = v * 2 + (pos + i < bits.length ? bits[pos + i] : 0);
        return v;
    }

    static byte[] concat(byte[] a, byte[] b) {
        byte[] r = Arrays.copyOf(a, a.length + b.length);
        System.arraycopy(b, 0, r, a.length, b.length);
        return r;
    }

    private static void putU32(byte[] m, int off, long v) {
        m[off] = (byte) (v >>> 24); m[off + 1] = (byte) (v >>> 16); m[off + 2] = (byte) (v >>> 8); m[off + 3] = (byte) v;
    }

    /** Check code: first checkBits bits of SHA-256("kck1" || u32 bit length || data bytes) (at most 256). */
    public static byte[] checkCode(byte[] dataBits, long checkBits) {
        if (checkBits == 0) return new byte[0];
        byte[] body = bitsToBytes(dataBits), msg = new byte[8 + body.length];
        msg[0] = 0x6b; msg[1] = 0x63; msg[2] = 0x6b; msg[3] = 0x31;
        putU32(msg, 4, dataBits.length);
        System.arraycopy(body, 0, msg, 8, body.length);
        byte[] h = bytesToBits(sha256(msg));
        // JS: .slice(0, checkBits); a negative count drops bits from the end (unreachable from the UI, kept for parity)
        long end = checkBits < 0 ? Math.max(0, h.length + checkBits) : Math.min(h.length, checkBits);
        return Arrays.copyOf(h, (int) end);
    }

    private static byte[] surplusMsg(byte[] data) {
        byte[] body = bitsToBytes(data), msg = new byte[12 + body.length];
        msg[0] = 0x6b; msg[1] = 0x63; msg[2] = 0x6b; msg[3] = 0x70;
        putU32(msg, 4, data.length);
        System.arraycopy(body, 0, msg, 12, body.length);
        return msg;
    }

    /** Surplus bits (v1.1+): SHA-256("kckp" || u32 bit length || u32 counter || data) blocks, counter 0, 1, ... */
    public static byte[] surplusBits(byte[] dataBits, int n) {
        byte[] msg = surplusMsg(dataBits), out = new byte[n];
        int got = 0;
        for (int ctr = 0; got < n; ctr++) {
            putU32(msg, 8, ctr);
            byte[] h = bytesToBits(sha256(msg));
            int k = Math.min(h.length, n - got);
            System.arraycopy(h, 0, out, got, k);
            got += k;
        }
        return out;
    }

    /** "none", "zero" (v1.0 style), "surplus" (v1.1+) or null (reject). */
    public static String paddingKind(byte[] data, byte[] pad, int padFrom) {
        int n = pad.length - padFrom;
        if (n <= 0) return "none";
        boolean zero = true;
        for (int i = padFrom; i < pad.length; i++) if (pad[i] != 0) { zero = false; break; }
        if (zero) return "zero";
        byte[] msg = surplusMsg(data), h = null;
        for (int j = 0; j < n; j++) {
            if (j % 256 == 0) { putU32(msg, 8, j / 256); h = sha256(msg); }
            if (((h[(j % 256) >> 3] >> (7 - (j & 7))) & 1) != pad[padFrom + j]) return null;
        }
        return "surplus";
    }

    public static String paddingKind(byte[] data, byte[] pad) { return paddingKind(data, pad, 0); }

    private static final class Stream {
        final byte[] bits; final int L;
        Stream(byte[] bits, int L) { this.bits = bits; this.L = L; }
    }

    private static Stream streamOf(byte[] dataBits, long checkBits) {
        byte[] body = concat(dataBits, checkCode(dataBits, checkBits));
        return new Stream(concat(body, surplusBits(dataBits, SURPLUS_MAX)), body.length);
    }

    // ---------- pool ----------
    public static final class Pool {
        public final String[] chars;
        public final int[] counts;
        final Map<String, Integer> index = new HashMap<>();

        public Pool(String kanji, int[] counts) {
            int[] cps = kanji.codePoints().toArray();
            if (cps.length != 4096 || counts.length != 4096) throw new KckException("pool must have 4096 kanji");
            chars = new String[4096];
            for (int i = 0; i < 4096; i++) { chars[i] = new String(Character.toChars(cps[i])); index.put(chars[i], i); }
            this.counts = counts.clone();
        }

        public Integer indexOf(String c) { return index.get(c); }
    }

    // ---------- tokens / results ----------
    public enum Type { KANJI, HEX, ALPHA }

    public static final class Token {
        public final Type type;
        public final String ch;
        public final int index;      // kanji pool index (else -1)
        public final int[] colors;   // kanji: one per stroke; hex/alpha: a single color
        Token(Type type, String ch, int index, int[] colors) { this.type = type; this.ch = ch; this.index = index; this.colors = colors; }
        public int color() { return colors[0]; }
        static Token kanji(Pool p, int idx, int[] colors) { return new Token(Type.KANJI, p.chars[idx], idx, colors); }
        static Token hex(char c, int color) { return new Token(Type.HEX, String.valueOf(c), -1, new int[]{color}); }
        static Token alpha(int v7) { return new Token(Type.ALPHA, String.valueOf(ALPHA.charAt(v7 >> 2)), -1, new int[]{v7 & 3}); }
        static Token alpha(int glyph, int color) { return new Token(Type.ALPHA, String.valueOf(ALPHA.charAt(glyph)), -1, new int[]{color}); }
    }

    public static final class Encoded {
        public final List<Token> tokens; public final String text;
        public final int totalBits, dataBits, writtenBits, surplus; public final long checkBits;
        Encoded(List<Token> tokens, String text, int totalBits, int dataBits, long checkBits, int writtenBits) {
            this.tokens = tokens; this.text = text; this.totalBits = totalBits; this.dataBits = dataBits;
            this.checkBits = checkBits; this.writtenBits = writtenBits; this.surplus = writtenBits - totalBits;
        }
        public int count(Type t) { int n = 0; for (Token k : tokens) if (k.type == t) n++; return n; }
    }

    private static String header(String prefix, long dataLen, long checkBits) {
        return prefix + "(" + dataLen + (checkBits != 0 ? "+" + checkBits : "") + "bit)";
    }

    // ---------- encode ----------
    public static Encoded encodeBits(Pool pool, byte[] dataBits, long checkBits) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        int pos = 0;
        while (s.L - pos >= 12) {
            int idx = readInt(s.bits, pos, 12); pos += 12;
            int[] colors = new int[pool.counts[idx]];
            for (int k = 0; k < colors.length; k++) { colors[k] = readInt(s.bits, pos, 2); pos += 2; }
            tokens.add(Token.kanji(pool, idx, colors));
        }
        while (pos < s.L) {
            tokens.add(Token.hex(HEX.charAt(readInt(s.bits, pos, 4)), readInt(s.bits, pos + 4, 2))); pos += 6;
        }
        return new Encoded(tokens, formatTokens(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, pos);
    }

    public static Encoded encodeHex(Pool pool, String hex, long checkBits) { return encodeBits(pool, hexToBits(hex), checkBits); }

    public static String formatTokens(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("", dataLen, checkBits));
        for (Token t : tokens) { sb.append(t.ch); for (int c : t.colors) sb.append(c); }
        return sb.toString();
    }

    public static Encoded encodeAlpha(byte[] dataBits, long checkBits) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        for (int pos = 0; pos < s.L; pos += 7) tokens.add(Token.alpha(readInt(s.bits, pos, 5), readInt(s.bits, pos + 5, 2)));
        return new Encoded(tokens, formatAlpha(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, tokens.size() * 7);
    }

    public static String formatAlpha(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("A", dataLen, checkBits));
        for (int i = 0; i < tokens.size(); i++) {
            if (i != 0 && i % 4 == 0) sb.append(' ');
            sb.append(tokens.get(i).ch).append(tokens.get(i).color());
        }
        return sb.toString();
    }

    /** Mixed mode. alphaPos: 1-based positions that are alpha glyphs. tailAlpha: finish with glyphs ('alpha' tail). */
    public static Encoded encodeMixed(Pool pool, byte[] dataBits, long checkBits, Set<Integer> alphaPos, boolean tailAlpha) {
        Stream s = streamOf(dataBits, checkBits);
        List<Token> tokens = new ArrayList<>();
        int pos = 0;
        boolean alphaRest = false;
        for (int i = 1; pos < s.L; i++) {
            boolean isAlpha = alphaRest || alphaPos.contains(i);
            if (!isAlpha && tailAlpha) {
                int idx = readInt(s.bits, pos, 12);
                if (s.L - pos < 12 + 2 * pool.counts[idx]) { alphaRest = isAlpha = true; }
            }
            if (isAlpha) { tokens.add(Token.alpha(readInt(s.bits, pos, 5), readInt(s.bits, pos + 5, 2))); pos += 7; }
            else {
                int idx = readInt(s.bits, pos, 12); pos += 12;
                int[] colors = new int[pool.counts[idx]];
                for (int k = 0; k < colors.length; k++) { colors[k] = readInt(s.bits, pos, 2); pos += 2; }
                tokens.add(Token.kanji(pool, idx, colors));
            }
        }
        return new Encoded(tokens, formatMixed(tokens, dataBits.length, checkBits), s.L, dataBits.length, checkBits, pos);
    }

    public static String formatMixed(List<Token> tokens, long dataLen, long checkBits) {
        StringBuilder sb = new StringBuilder(header("M", dataLen, checkBits));
        for (int i = 0; i < tokens.size(); i++) {
            if (i != 0) sb.append(' ');
            Token t = tokens.get(i);
            sb.append(t.ch);
            for (int c : t.colors) sb.append(c);
        }
        return sb.toString();
    }

    // ---------- uncertain color sequences ----------
    /** Raw expansions above this are refused (the JS would try and run out of time/memory). */
    static final double EXPAND_LIMIT = 8_000_000;

    public static List<int[]> expandColorSpec(String spec) {
        List<Integer> syms = new ArrayList<>(); // 0..3 or -1 for '?'
        List<int[]> groups = new ArrayList<>(); // {kind '(' or '[', start, len}
        int[] open = null;
        for (int k = 0; k < spec.length(); k++) {
            char ch = spec.charAt(k);
            if (ch == '(' || ch == '[') {
                if (open != null) throw new KckException("nested brackets");
                open = new int[]{ch, syms.size(), 0};
            } else if (ch == ')' || ch == ']') {
                if (open == null || (open[0] == '(') != (ch == ')')) throw new KckException("mismatched bracket");
                open[2] = syms.size() - open[1]; groups.add(open); open = null;
            } else if (ch == '?') syms.add(-1);
            else if (ch >= '0' && ch <= '3') syms.add(ch - '0');
            else throw new KckException("bad color char " + new String(Character.toChars(spec.codePointAt(k))));
        }
        if (open != null) throw new KckException("unclosed bracket");
        // guard against expansions the phone cannot hold (see EXPAND_LIMIT)
        double raw = 1;
        int restLen = syms.size();
        for (int[] g : groups) if (g[0] == '[') for (int i = 2; i <= g[2]; i++) raw *= i;
        for (int[] g : groups) if (g[0] == '(') raw *= (syms.size() - g[2] + 1);
        for (int v : syms) if (v < 0) raw *= 4;
        if (raw > EXPAND_LIMIT) throw new KckException("too many combinations (" + jsNumber(raw) + "+); narrow the uncertainty");
        List<int[]> variants = new ArrayList<>();
        int[] ids0 = new int[restLen];
        for (int i = 0; i < restLen; i++) ids0[i] = i;
        variants.add(ids0);
        for (int[] g : groups) {
            if (g[0] != '[') continue;
            List<int[]> next = new ArrayList<>();
            for (int[] v : variants) for (int[] p : permutations(Arrays.copyOfRange(v, g[1], g[1] + g[2]))) {
                int[] w = v.clone();
                System.arraycopy(p, 0, w, g[1], p.length);
                next.add(w);
            }
            variants = next;
        }
        for (int[] g : groups) {
            if (g[0] != '(') continue;
            boolean[] in = new boolean[syms.size()];
            for (int i = g[1]; i < g[1] + g[2]; i++) in[i] = true;
            List<int[]> next = new ArrayList<>();
            for (int[] v : variants) {
                int[] block = Arrays.stream(v).filter(x -> in[x]).toArray(), rest = Arrays.stream(v).filter(x -> !in[x]).toArray();
                for (int p = 0; p <= rest.length; p++) {
                    int[] w = new int[v.length];
                    System.arraycopy(rest, 0, w, 0, p);
                    System.arraycopy(block, 0, w, p, block.length);
                    System.arraycopy(rest, p, w, p + block.length, rest.length - p);
                    next.add(w);
                }
            }
            variants = next;
        }
        LinkedHashMap<String, int[]> out = new LinkedHashMap<>();
        for (int[] v : variants) {
            List<int[]> partial = new ArrayList<>();
            partial.add(new int[0]);
            for (int id : v) {
                int s = syms.get(id);
                List<int[]> np = new ArrayList<>();
                for (int[] a : partial) {
                    if (s < 0) for (int c = 0; c < 4; c++) np.add(append(a, c));
                    else np.add(append(a, s));
                }
                partial = np;
            }
            for (int[] a : partial) {
                StringBuilder key = new StringBuilder();
                for (int c : a) key.append(c);
                out.putIfAbsent(key.toString(), a);
            }
        }
        return new ArrayList<>(out.values());
    }

    private static int[] append(int[] a, int c) { int[] r = Arrays.copyOf(a, a.length + 1); r[a.length] = c; return r; }

    static List<int[]> permutations(int[] a) {
        List<int[]> res = new ArrayList<>();
        if (a.length <= 1) { res.add(a); return res; }
        for (int i = 0; i < a.length; i++) {
            int[] rest = new int[a.length - 1];
            System.arraycopy(a, 0, rest, 0, i);
            System.arraycopy(a, i + 1, rest, i, a.length - i - 1);
            for (int[] p : permutations(rest)) {
                int[] w = new int[a.length];
                w[0] = a[i];
                System.arraycopy(p, 0, w, 1, p.length);
                res.add(w);
            }
        }
        return res;
    }

    // ---------- parse ----------
    /** Parsed symbol: type, char, pool index (kanji), the written spec and the candidate option values. */
    public static final class PToken {
        public final Type type; public final String ch; public final int index; public final String spec;
        final List<int[]> colorOptions; // kanji/hex: color arrays
        final int[] valueOptions;       // alpha: 7-bit values
        PToken(Type type, String ch, int index, String spec, List<int[]> colorOptions, int[] valueOptions) {
            this.type = type; this.ch = ch; this.index = index; this.spec = spec; this.colorOptions = colorOptions; this.valueOptions = valueOptions;
        }
        public int optionCount() { return valueOptions != null ? valueOptions.length : colorOptions.size(); }
    }

    public static final class Parsed {
        public final long dataBits, checkBits; public final List<PToken> tokens;
        Parsed(long dataBits, long checkBits, List<PToken> tokens) { this.dataBits = dataBits; this.checkBits = checkBits; this.tokens = tokens; }
    }

    private static final Pattern H_TEXT = Pattern.compile("^[(（]([0-9]+)(?:\\+([0-9]+))?bit[)）]", Pattern.CASE_INSENSITIVE);
    private static final Pattern H_MIXED = Pattern.compile("^[Mm][(（]([0-9]+)(?:\\+([0-9]+))?bit[)）]", Pattern.CASE_INSENSITIVE);
    private static final Pattern H_ALPHA = Pattern.compile("^A[(（]([0-9]+)(?:\\+([0-9]+))?BIT[)）]");

    /** JS unary + on a digit string (doubles); clamped to long, which only matters for absurd headers. */
    private static long num(String s) {
        double d = Double.parseDouble(s);
        return d >= 9e15 ? (long) 9e15 : (long) d;
    }

    private static String cp(int c) { return new String(Character.toChars(c)); }

    private static String joinCps(int[] cps, int from) {
        StringBuilder sb = new StringBuilder();
        for (int i = from; i < cps.length; i++) sb.appendCodePoint(cps[i]);
        return sb.toString();
    }

    private static boolean isColorDigitOrQ(int d) { return (d >= '0' && d <= '3') || d == '?'; }

    /**
     * The color run after a kanji or hex digit (shared by parseText and parseMixed). Returns {spec, newI} via the
     * holder; throws if the count does not match.
     */
    private static String colorRun(int[] chars, int[] iRef, int need, String c) {
        int i = iRef[0], n = 0;
        StringBuilder spec = new StringBuilder();
        while (i < chars.length) {
            if (n < need) { String cn = colorName(chars[i]); if (cn != null) chars[i] = cn.charAt(0); }
            int d = chars[i];
            if (n == need && d != ')' && d != ']') break;
            if (isColorDigitOrQ(d)) n++;
            else if (d != '(' && d != ')' && d != '[' && d != ']') break;
            spec.appendCodePoint(d); i++;
        }
        iRef[0] = i;
        if (n != need) throw new KckException("\"" + c + "\" needs " + need + " colors, got " + n);
        return spec.toString();
    }

    public static Parsed parseText(Pool pool, String text) {
        String t = Normalizer.normalize(WS_RUN.matcher(text).replaceAll(""), Normalizer.Form.NFC);
        Matcher m = H_TEXT.matcher(t);
        if (!m.find()) throw new KckException("missing header like (256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        int[] chars = t.substring(m.end()).codePoints().toArray();
        List<PToken> tokens = new ArrayList<>();
        int[] iRef = {0};
        long budget = dataBits + checkBits;
        while (iRef[0] < chars.length) {
            String c = cp(chars[iRef[0]++]);
            int need;
            Type type; int index = -1; String ch;
            if (budget >= 12) {
                Integer idx = pool.indexOf(c);
                if (idx == null) throw new KckException("\"" + c + "\" is not in the kanji pool");
                index = idx; need = pool.counts[idx]; type = Type.KANJI; ch = c;
                budget -= 12 + 2L * need;
            } else {
                String lc = c.toLowerCase(Locale.ROOT);
                if (!HEX.contains(lc)) throw new KckException("expected hex char, got \"" + c + "\"");
                need = 1; type = Type.HEX; ch = lc; budget -= 6;
            }
            String spec = colorRun(chars, iRef, need, c);
            tokens.add(new PToken(type, ch, index, spec, expandColorSpec(spec), null));
            if (budget <= 0) break;
        }
        if (budget > 0) throw new KckException("text too short for header");
        if (iRef[0] < chars.length) throw new KckException("trailing characters: " + joinCps(chars, iRef[0]));
        return new Parsed(dataBits, checkBits, tokens);
    }

    public static Parsed parseAlpha(String text) {
        StringBuilder sb = new StringBuilder();
        String w = WS_RUN.matcher(text).replaceAll("");
        for (int k = 0; k < w.length(); k++) {
            char ch = w.charAt(k);
            String cn = colorName(ch);
            sb.append(cn != null ? cn : String.valueOf(ch));
        }
        String t = sb.toString().toUpperCase(Locale.ROOT);
        Matcher m = H_ALPHA.matcher(t);
        if (!m.find()) throw new KckException("missing header like A(256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        String body = t.substring(m.end());
        long n = (dataBits + checkBits + 6) / 7;
        if (dataBits + checkBits <= 0) n = 0;
        if (body.length() != 2 * n) throw new KckException("expected " + n + " symbols (" + 2 * n + " chars), got " + body.length() + " chars");
        List<PToken> tokens = new ArrayList<>();
        for (int i = 0; i < n; i++) {
            char g = body.charAt(2 * i), c = body.charAt(2 * i + 1);
            if (g != '?' && ALPHA.indexOf(g) < 0) throw new KckException("\"" + g + "\" is not in the alpha set (0, 1, 8, U are excluded)");
            if (!isColorDigitOrQ(c)) throw new KckException("bad color \"" + c + "\" after \"" + g + "\"");
            tokens.add(new PToken(Type.ALPHA, String.valueOf(g), -1, String.valueOf(c), null, alphaOptions(g, c)));
        }
        return new Parsed(dataBits, checkBits, tokens);
    }

    private static int[] alphaOptions(int g, int c) {
        int[] gs, cs;
        if (g == '?') { gs = new int[32]; for (int a = 0; a < 32; a++) gs[a] = a; } else gs = new int[]{ALPHA.indexOf(g)};
        if (c == '?') cs = new int[]{0, 1, 2, 3}; else cs = new int[]{c - '0'};
        int[] o = new int[gs.length * cs.length];
        int k = 0;
        for (int a : gs) for (int b : cs) o[k++] = a * 4 + b;
        return o;
    }

    private static boolean isAlnumQ(int c) {
        return (c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '?';
    }

    public static Parsed parseMixed(Pool pool, String text) {
        String t = Normalizer.normalize(WS_RUN.matcher(text).replaceAll(""), Normalizer.Form.NFC);
        Matcher m = H_MIXED.matcher(t);
        if (!m.find()) throw new KckException("missing header like M(256+12bit)");
        long dataBits = num(m.group(1)), checkBits = m.group(2) == null ? DEFAULT_CHECK_BITS : num(m.group(2));
        int[] chars = t.substring(m.end()).codePoints().toArray();
        List<PToken> tokens = new ArrayList<>();
        int[] iRef = {0};
        long budget = dataBits + checkBits;
        while (iRef[0] < chars.length && budget > 0) {
            int c = chars[iRef[0]++];
            if (isAlnumQ(c)) {
                char g = Character.toUpperCase((char) c);
                String col = null;
                if (iRef[0] < chars.length) { String cn = colorName(chars[iRef[0]]); col = cn != null ? cn : cp(chars[iRef[0]]); }
                iRef[0]++;
                if (g != '?' && ALPHA.indexOf(g) < 0) throw new KckException("\"" + g + "\" is not in the alpha set (0, 1, 8, U are excluded)");
                if (col == null || !containsColorChar(col)) throw new KckException("bad color \"" + (col == null ? "" : col) + "\" after \"" + g + "\"");
                tokens.add(new PToken(Type.ALPHA, String.valueOf(g), -1, col, null, alphaOptions(g, col.charAt(0))));
                budget -= 7;
            } else {
                String cs = cp(c);
                Integer idx = pool.indexOf(cs);
                if (idx == null) throw new KckException("\"" + cs + "\" is not in the kanji pool");
                int need = pool.counts[idx];
                String spec = colorRun(chars, iRef, need, cs);
                tokens.add(new PToken(Type.KANJI, cs, idx, spec, expandColorSpec(spec), null));
                budget -= 12 + 2L * need;
            }
        }
        if (budget > 0) throw new KckException("text too short for header");
        if (iRef[0] < chars.length) throw new KckException("trailing characters: " + joinCps(chars, iRef[0]));
        return new Parsed(dataBits, checkBits, tokens);
    }

    private static boolean containsColorChar(String s) {
        for (int k = 0; k < s.length(); k++) if (isColorDigitOrQ(s.charAt(k))) return true;
        return false;
    }

    // ---------- decode ----------
    public static final class Candidate {
        public final byte[] bits; public final String hex, text, padding; public final List<Token> tokens;
        Candidate(byte[] bits, String hex, String text, List<Token> tokens, String padding) {
            this.bits = bits; this.hex = hex; this.text = text; this.tokens = tokens; this.padding = padding;
        }
    }

    public static final class Decoded {
        public final List<Candidate> candidates; public final long tried; public final double total;
        public final long dataBits, checkBits;
        Decoded(List<Candidate> c, long tried, double total, long dataBits, long checkBits) {
            this.candidates = c; this.tried = tried; this.total = total; this.dataBits = dataBits; this.checkBits = checkBits;
        }
    }

    /** Lets a long decode be abandoned (e.g. when the app goes to the background). */
    public interface Cancel { boolean cancelled(); }

    private enum Mode { TEXT, ALPHA, MIXED }

    public static Decoded decodeText(Pool pool, String text) { return decode(pool, parseText(pool, text), Mode.TEXT, MAX_CANDIDATES, null); }
    public static Decoded decodeAlpha(String text) { return decode(null, parseAlpha(text), Mode.ALPHA, MAX_CANDIDATES, null); }
    public static Decoded decodeMixed(Pool pool, String text) { return decode(pool, parseMixed(pool, text), Mode.MIXED, MAX_CANDIDATES, null); }

    private static final Pattern IS_ALPHA = Pattern.compile("^" + JS_WS + "*[Aa]" + JS_WS + "*[(（]");
    private static final Pattern IS_MIXED = Pattern.compile("^" + JS_WS + "*[Mm]" + JS_WS + "*[(（]");
    public static boolean isAlphaText(String text) { return IS_ALPHA.matcher(text).find(); }
    public static boolean isMixedText(String text) { return IS_MIXED.matcher(text).find(); }

    public static Decoded decodeAny(Pool pool, String text) { return decodeAny(pool, text, null); }

    public static Decoded decodeAny(Pool pool, String text, Cancel cancel) {
        if (isAlphaText(text)) return decode(null, parseAlpha(text), Mode.ALPHA, MAX_CANDIDATES, cancel);
        if (isMixedText(text)) return decode(pool, parseMixed(pool, text), Mode.MIXED, MAX_CANDIDATES, cancel);
        return decode(pool, parseText(pool, text), Mode.TEXT, MAX_CANDIDATES, cancel);
    }

    /** The written bits of one option of a parsed symbol. */
    private static byte[] optionBits(PToken t, int o) {
        if (t.type == Type.ALPHA) {
            int v = t.valueOptions[o];
            byte[] b = new byte[7];
            for (int k = 6; k >= 0; k--) b[6 - k] = (byte) ((v >> k) & 1);
            return b;
        }
        int[] col = t.colorOptions.get(o);
        int head = t.type == Type.KANJI ? 12 : 4, v = t.type == Type.KANJI ? t.index : HEX.indexOf(t.ch);
        byte[] b = new byte[head + 2 * col.length];
        for (int k = head - 1; k >= 0; k--) b[head - 1 - k] = (byte) ((v >> k) & 1);
        for (int s = 0; s < col.length; s++) { b[head + 2 * s] = (byte) (col[s] >> 1); b[head + 2 * s + 1] = (byte) (col[s] & 1); }
        return b;
    }

    private static Token resolved(Pool pool, PToken t, int o) {
        if (t.type == Type.ALPHA) return Token.alpha(t.valueOptions[o]);
        int[] col = t.colorOptions.get(o);
        if (t.type == Type.KANJI) return new Token(Type.KANJI, t.ch, t.index, col);
        return Token.hex(t.ch.charAt(0), col[0]);
    }

    private static Decoded decode(Pool pool, Parsed p, Mode mode, int maxCandidates, Cancel cancel) {
        double total = 1;
        for (PToken t : p.tokens) total *= t.optionCount();
        if (total > maxCandidates) throw new KckException("too many combinations (" + jsNumber(total) + "); narrow the uncertainty");
        int nt = p.tokens.size();
        byte[][][] ob = new byte[nt][][];
        int len = 0;
        for (int k = 0; k < nt; k++) {
            PToken t = p.tokens.get(k);
            ob[k] = new byte[t.optionCount()][];
            for (int o = 0; o < ob[k].length; o++) ob[k][o] = optionBits(t, o);
        }
        int[] choice = new int[nt];
        for (int k = 0; k < nt; k++) len += ob[k][0].length;  // option lengths are equal within a token
        int dataN = (int) p.dataBits, L = (int) (p.dataBits + p.checkBits);
        List<Candidate> results = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        long tried = 0;
        byte[] bits = new byte[len];
        for (;;) {
            if (cancel != null && (tried & 0xFFF) == 0 && cancel.cancelled()) throw new KckException("cancelled");
            tried++;
            int at = 0;
            for (int k = 0; k < nt; k++) { byte[] b = ob[k][choice[k]]; System.arraycopy(b, 0, bits, at, b.length); at += b.length; }
            byte[] data = Arrays.copyOf(bits, dataN);
            byte[] cc = checkCode(data, p.checkBits);
            boolean ok = true;
            for (int j = 0; j < cc.length; j++) {
                // JS compares against chk[j] (undefined past the end of the written bits -> mismatch)
                int idx = dataN + j;
                if (idx >= L || idx >= bits.length || cc[j] != bits[idx]) { ok = false; break; }
            }
            String padding = ok ? paddingKind(data, bits, Math.min(L, bits.length)) : null;
            if (padding != null) {
                String dk = bitsKey(data);
                if (seen.add(dk)) {
                    List<Token> tokens = new ArrayList<>(nt);
                    for (int k = 0; k < nt; k++) tokens.add(resolved(pool, p.tokens.get(k), choice[k]));
                    String text = mode == Mode.ALPHA ? formatAlpha(tokens, p.dataBits, p.checkBits)
                            : mode == Mode.MIXED ? formatMixed(tokens, p.dataBits, p.checkBits)
                            : formatTokens(tokens, p.dataBits, p.checkBits);
                    results.add(new Candidate(data, bitsToHex(data), text, tokens, padding));
                }
            }
            int k = 0;
            while (k < nt && ++choice[k] == ob[k].length) choice[k++] = 0;
            if (k == nt) break;
        }
        return new Decoded(results, tried, total, p.dataBits, p.checkBits);
    }

    private static String bitsKey(byte[] b) {
        char[] c = new char[b.length];
        for (int i = 0; i < b.length; i++) c[i] = (char) ('0' + b[i]);
        return new String(c);
    }

    /** Number formatting like JS Number#toString for the values that reach messages. */
    static String jsNumber(double d) {
        if (d == Math.rint(d) && Math.abs(d) < 9.007199254740992E15) return Long.toString((long) d);
        if (Double.isInfinite(d)) return d > 0 ? "Infinity" : "-Infinity";
        if (Math.abs(d) < 1e21) return new BigDecimal(Double.toString(d)).toPlainString();
        String s = Double.toString(d).replace("E", "e+");
        return s.replace(".0e", "e");
    }

    // ---------- hash mode ----------
    /** UTF-8 like TextEncoder (lone surrogates become U+FFFD). */
    static byte[] utf8(String s) {
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (Character.isHighSurrogate(c) && i + 1 < s.length() && Character.isLowSurrogate(s.charAt(i + 1))) { sb.append(c).append(s.charAt(++i)); }
            else if (Character.isSurrogate(c)) sb.append('\uFFFD');
            else sb.append(c);
        }
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    /** PBKDF2-HMAC-SHA256(NFC(passphrase), "kanji-color-key/v1:" + salt, iterations), 256 bit. Same as deriveKey(). */
    public static byte[] deriveKey(String passphrase, String salt, int iterations) {
        return pbkdf2Sha256(utf8(Normalizer.normalize(passphrase, Normalizer.Form.NFC)), utf8("kanji-color-key/v1:" + salt), iterations, 32);
    }

    static byte[] pbkdf2Sha256(byte[] password, byte[] salt, int iterations, int dkLen) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            // an empty password is legal in PBKDF2 / WebCrypto, but SecretKeySpec refuses empty keys
            if (password.length == 0) mac.init(new SecretKeySpec(new byte[64], "HmacSHA256")); // HMAC zero-pads keys to 64 bytes
            else mac.init(new SecretKeySpec(password, "HmacSHA256"));
            byte[] out = new byte[dkLen];
            int blocks = (dkLen + 31) / 32;
            for (int bi = 1; bi <= blocks; bi++) {
                mac.update(salt);
                mac.update(new byte[]{(byte) (bi >>> 24), (byte) (bi >>> 16), (byte) (bi >>> 8), (byte) bi});
                byte[] u = mac.doFinal(), t = u.clone();
                for (int it = 1; it < iterations; it++) {
                    u = mac.doFinal(u);
                    for (int j = 0; j < 32; j++) t[j] ^= u[j];
                }
                System.arraycopy(t, 0, out, (bi - 1) * 32, Math.min(32, dkLen - (bi - 1) * 32));
                Arrays.fill(t, (byte) 0);
            }
            return out;
        } catch (java.security.GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    private static final SecureRandom RNG = new SecureRandom();

    /** Random bits from SecureRandom (the web app uses crypto.getRandomValues). */
    public static byte[] randomBits(int n) {
        byte[] b = new byte[(n + 7) / 8];
        RNG.nextBytes(b);
        byte[] bits = Arrays.copyOf(bytesToBits(b), n);
        Arrays.fill(b, (byte) 0);
        return bits;
    }
