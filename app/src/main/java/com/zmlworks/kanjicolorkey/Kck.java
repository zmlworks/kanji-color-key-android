    public static final class Candidate {
        public final byte[] bits; public final String hex, text, padding; public final List<Token> tokens;
        Candidate(byte[] bits, String hex, String text, List<Token> tokens, String padding) {
            this.bits = bits; this.hex = hex; this.text = text; this.tokens = tokens; this.padding = padding;
        }
    }

    public static final class Decoded {
        public final List<Candidate> candidates; public final long tried; public final double total;
        public final long dataBits, checkBits;
        /** Mixed / KF only (else null): "off", "always", "fallback" or "skipped" (see searchWithLookalikes). */
        public final String lookalike;
        public final boolean fixed;
        Decoded(List<Candidate> c, long tried, double total, long dataBits, long checkBits) { this(c, tried, total, dataBits, checkBits, null, false); }
        Decoded(List<Candidate> c, long tried, double total, long dataBits, long checkBits, String lookalike, boolean fixed) {
            this.candidates = c; this.tried = tried; this.total = total; this.dataBits = dataBits; this.checkBits = checkBits;
            this.lookalike = lookalike; this.fixed = fixed;
        }
        Decoded with(long tried, String lookalike) { return new Decoded(candidates, tried, total, dataBits, checkBits, lookalike, fixed); }
    }

    /** Lets a long decode be abandoned (e.g. when the app goes to the background). */
    public interface Cancel { boolean cancelled(); }

    /** Decode options (the JS o = { kana, maxCandidates, swapLookalikes, lookalikeFallback }). */
    public static final class Options {
        public KanaSet kana;
        public int maxCandidates = MAX_CANDIDATES;
        /** Always try the hiragana/katakana partner of お/オ き/キ け/ケ さ/サ ほ/ホ も/モ. */
        public boolean swapLookalikes = false;
        /** Try the partners automatically when nothing matches. */
        public boolean lookalikeFallback = true;
        public Options() {}
        public Options(KanaSet kana) { this.kana = kana; }
        public Options swap(boolean v) { swapLookalikes = v; return this; }
        public Options fallback(boolean v) { lookalikeFallback = v; return this; }
        public Options max(int v) { maxCandidates = v; return this; }
    }

    private enum Mode { TEXT, ALPHA, MIXED, KF }

    public static Decoded decodeText(Pool pool, String text) { return decodeText(pool, text, new Options(), null); }
    public static Decoded decodeAlpha(String text) { return decodeAlpha(text, new Options(), null); }
    public static Decoded decodeMixed(Pool pool, String text) { return decodeMixed(pool, text, new Options(), null); }

    static Decoded decodeText(Pool pool, String text, Options o, Cancel cancel) {
        Parsed p = parseText(pool, text);
        return search(pool, null, p, alts(pool, null, p, false), Mode.TEXT, o.maxCandidates, cancel);
    }

    static Decoded decodeAlpha(String text, Options o, Cancel cancel) {
        Parsed p = parseAlpha(text);
        return search(null, null, p, alts(null, null, p, false), Mode.ALPHA, o.maxCandidates, cancel);
    }

    public static Decoded decodeMixed(Pool pool, String text, Options o, Cancel cancel) {
        Parsed p = parseMixed(pool, text, o.kana);
        return searchWithLookalikes(pool, o.kana, p, Mode.MIXED, o, cancel);
    }

    public static Decoded decodeKanaFixed(KanaSet kana, String text, Options o, Cancel cancel) {
        Parsed p = parseKanaFixed(kana, text);
        return searchWithLookalikes(null, kana, p, Mode.KF, o, cancel);
    }

    private static final Pattern IS_ALPHA = Pattern.compile("^" + JS_WS + "*[Aa]" + JS_WS + "*[(（]");
    private static final Pattern IS_KF = Pattern.compile("^" + JS_WS + "*[Kk]" + JS_WS + "*[Ff]" + JS_WS + "*[(（]");
    private static final Pattern IS_MIXED = Pattern.compile("^" + JS_WS + "*[MmKk]" + JS_WS + "*[(（]");
    public static boolean isAlphaText(String text) { return IS_ALPHA.matcher(text).find(); }
    public static boolean isKanaFixedText(String text) { return IS_KF.matcher(text).find(); }
    /** "M(" or the kana prototype's "K(". */
    public static boolean isMixedText(String text) { return IS_MIXED.matcher(text).find(); }

    public static Decoded decodeAny(Pool pool, String text) { return decodeAny(pool, text, new Options(), null); }

    public static Decoded decodeAny(Pool pool, String text, Cancel cancel) { return decodeAny(pool, text, new Options(), cancel); }

    /** Dispatch on the header: "A(" alpha, "KF(" fixed-length kana, "M(" / "K(" mixed, "(" kanji. Kana need o.kana. */
    public static Decoded decodeAny(Pool pool, String text, Options o, Cancel cancel) {
        if (isAlphaText(text)) return decodeAlpha(text, o, cancel);
        if (isKanaFixedText(text)) return decodeKanaFixed(needKana(o.kana), text, o, cancel);
        if (isMixedText(text)) return decodeMixed(pool, text, o, cancel);
        return decodeText(pool, text, o, cancel);
    }

    /** One alternative reading of a parsed symbol: its written bits and the token it stands for. */
    private static final class Alt {
        final byte[] bits; final Token token;
        Alt(byte[] bits, Token token) { this.bits = bits; this.token = token; }
    }

    private static byte[] symbolBits(int v, int head, int[] colors) {
        byte[] b = new byte[head + 2 * colors.length];
        for (int k = head - 1; k >= 0; k--) b[head - 1 - k] = (byte) ((v >> k) & 1);
        for (int s = 0; s < colors.length; s++) { b[head + 2 * s] = (byte) (colors[s] >> 1); b[head + 2 * s + 1] = (byte) (colors[s] & 1); }
        return b;
    }

    /**
     * Alternatives of a parsed symbol. With swap, a look-alike kana also tries its hiragana/katakana partner when the
     * stroke count is the same (so the layout is unchanged) or it is a one-color kana.
     */
    private static List<Alt> symbolAlts(Pool pool, KanaSet kana, PToken tk, boolean swap) {
        List<Alt> out = new ArrayList<>();
        switch (tk.type) {
            case ALPHA:
                for (int v : tk.valueOptions) out.add(new Alt(symbolBits(v, 7, new int[0]), Token.alpha(v)));
                return out;
            case KANJI:
                for (int[] col : tk.colorOptions) out.add(new Alt(symbolBits(tk.index, 12, col), new Token(Type.KANJI, tk.ch, tk.index, col)));
                return out;
            case HEX:
                for (int[] col : tk.colorOptions) out.add(new Alt(symbolBits(HEX.indexOf(tk.ch), 4, col), Token.hex(tk.ch.charAt(0), col[0])));
                return out;
            default:
                break;
        }
        List<Integer> idx = new ArrayList<>();
        idx.add(tk.index);
        String q = swap ? PARTNER.get(tk.ch) : null;
        if (q != null && kana.indexOf(q) != null && (tk.type == Type.KANA_GLYPH || kana.counts[kana.indexOf(q)] == kana.counts[tk.index])) idx.add(kana.indexOf(q));
        for (int ix : idx) for (int[] col : tk.colorOptions) {
            if (tk.type == Type.KANA_GLYPH) { out.add(new Alt(symbolBits(ix, 5, col), Token.kanaGlyph(kana, ix, col[0]))); continue; }
            int[] colors = Arrays.copyOf(col, Math.max(col.length, kana.counts[ix])); // KF: 4th stroke black
            out.add(new Alt(symbolBits(ix, 5, col), Token.kana(kana, ix, colors)));
        }
        if (tk.glyphAlt) for (int ix : idx) {
            int c = tk.colorOptions.get(0)[0];
            out.add(new Alt(symbolBits(ix, 5, new int[]{c}), Token.kanaGlyph(kana, ix, c)));
        }
        return out;
    }

    private static List<List<Alt>> alts(Pool pool, KanaSet kana, Parsed p, boolean swap) {
        List<List<Alt>> a = new ArrayList<>(p.tokens.size());
        for (PToken t : p.tokens) a.add(symbolAlts(pool, kana, t, swap));
        return a;
    }

    private static double product(List<List<Alt>> alts) {
        double total = 1;
        for (List<Alt> a : alts) total *= a.size();
        return total;
    }

    /** Look-alike retry: lookalike = "off" (not tried), "always" (swapLookalikes), "fallback" (the normal search found
     * nothing, so the partners were tried too; tried counts both runs) or "skipped" (the fallback would be too large). */
    private static Decoded searchWithLookalikes(Pool pool, KanaSet kana, Parsed p, Mode mode, Options o, Cancel cancel) {
        Decoded r0 = search(pool, kana, p, alts(pool, kana, p, o.swapLookalikes), mode, o.maxCandidates, cancel);
        Decoded r = r0.with(r0.tried, o.swapLookalikes ? "always" : "off");
        if (!r.candidates.isEmpty() || o.swapLookalikes || !o.lookalikeFallback) return r;
        List<List<Alt>> b = alts(pool, kana, p, true);
        double totalB = product(b);
        if (totalB == r.total) return r;
        if (totalB > o.maxCandidates) return r.with(r.tried, "skipped");
        Decoded r2 = search(pool, kana, p, b, mode, o.maxCandidates, cancel);
        return r2.with(r.tried + r2.tried, "fallback");
    }

    /** Enumerate every combination; keep those whose check matches and whose padding is the surplus (or all zero, v1.0). */
    private static Decoded search(Pool pool, KanaSet kana, Parsed p, List<List<Alt>> alts, Mode mode, int maxCandidates, Cancel cancel) {
        double total = product(alts);
        if (total > maxCandidates) throw new KckException("too many combinations (" + jsNumber(total) + "); narrow the uncertainty");
        int nt = alts.size(), maxLen = 0;
        for (List<Alt> a : alts) { int m = 0; for (Alt x : a) m = Math.max(m, x.bits.length); maxLen += m; }
        int[] choice = new int[nt];
        int dataN = (int) p.dataBits, L = (int) (p.dataBits + p.checkBits);
        List<Candidate> results = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        long tried = 0;
        byte[] bits = new byte[maxLen];
        for (;;) {
            if (cancel != null && (tried & 0xFFF) == 0 && cancel.cancelled()) throw new KckException("cancelled");
            tried++;
            int at = 0;
            for (int k = 0; k < nt; k++) { byte[] b = alts.get(k).get(choice[k]).bits; System.arraycopy(b, 0, bits, at, b.length); at += b.length; }
            byte[] data = Arrays.copyOf(bits, Math.min(dataN, at));
            byte[] cc = checkCode(data, p.checkBits);
            boolean ok = true;
            for (int j = 0; j < cc.length; j++) {
                // JS compares against chk[j] (undefined past the end of the written bits -> mismatch)
                int idx = dataN + j;
                if (idx >= L || idx >= at || cc[j] != bits[idx]) { ok = false; break; }
            }
            String padding = ok ? paddingKind(data, bits, Math.min(L, at), at) : null;
            if (padding != null) {
                String dk = bitsKey(data);
                if (seen.add(dk)) {
                    List<Token> tokens = new ArrayList<>(nt);
                    for (int k = 0; k < nt; k++) tokens.add(alts.get(k).get(choice[k]).token);
                    String text = mode == Mode.ALPHA ? formatAlpha(tokens, p.dataBits, p.checkBits)
                            : mode == Mode.MIXED ? formatMixed(tokens, p.dataBits, p.checkBits)
                            : mode == Mode.KF ? formatKanaFixed(tokens, p.dataBits, p.checkBits)
                            : formatTokens(tokens, p.dataBits, p.checkBits);
                    results.add(new Candidate(data, bitsToHex(data), text, tokens, padding));
                }
            }
            int k = 0;
            while (k < nt && ++choice[k] == alts.get(k).size()) choice[k++] = 0;
            if (k == nt) break;
        }
        return new Decoded(results, tried, total, p.dataBits, p.checkBits, null, mode == Mode.KF);
    }

    private static String bitsKey(byte[] b) {
        char[] c = new char[b.length];
        for (int i = 0; i < b.length; i++) c[i] = (char) ('0' + b[i]);
        return new String(c);
    }

    /** Number formatting like JS Number#toString for the values that reach messages. */
    static String jsNumber(double d) {
        if (d == Math.rint(d) && Math.abs(d) < 9.007199254740992E15) return Long.toString((long) d);
        if (Double.isInfinite(d)) return d > 0 ? "Infinity" : "-Infinity";
        if (Math.abs(d) < 1e21) return new BigDecimal(Double.toString(d)).toPlainString();
        String s = Double.toString(d).replace("E", "e+");
        return s.replace(".0e", "e");
    }

    // ---------- hash mode ----------
    /** UTF-8 like TextEncoder (lone surrogates become U+FFFD). */
    static byte[] utf8(String s) {
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (Character.isHighSurrogate(c) && i + 1 < s.length() && Character.isLowSurrogate(s.charAt(i + 1))) { sb.append(c).append(s.charAt(++i)); }
            else if (Character.isSurrogate(c)) sb.append('\uFFFD');
            else sb.append(c);
        }
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    /** PBKDF2-HMAC-SHA256(NFC(passphrase), "kanji-color-key/v1:" + salt, iterations), 256 bit. Same as deriveKey(). */
    public static byte[] deriveKey(String passphrase, String salt, int iterations) {
        return pbkdf2Sha256(utf8(Normalizer.normalize(passphrase, Normalizer.Form.NFC)), utf8("kanji-color-key/v1:" + salt), iterations, 32);
    }

    static byte[] pbkdf2Sha256(byte[] password, byte[] salt, int iterations, int dkLen) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            // an empty password is legal in PBKDF2 / WebCrypto, but SecretKeySpec refuses empty keys
            if (password.length == 0) mac.init(new SecretKeySpec(new byte[64], "HmacSHA256")); // HMAC zero-pads keys to 64 bytes
            else mac.init(new SecretKeySpec(password, "HmacSHA256"));
            byte[] out = new byte[dkLen];
            int blocks = (dkLen + 31) / 32;
            for (int bi = 1; bi <= blocks; bi++) {
                mac.update(salt);
                mac.update(new byte[]{(byte) (bi >>> 24), (byte) (bi >>> 16), (byte) (bi >>> 8), (byte) bi});
                byte[] u = mac.doFinal(), t = u.clone();
                for (int it = 1; it < iterations; it++) {
                    u = mac.doFinal(u);
                    for (int j = 0; j < 32; j++) t[j] ^= u[j];
                }
                System.arraycopy(t, 0, out, (bi - 1) * 32, Math.min(32, dkLen - (bi - 1) * 32));
                Arrays.fill(t, (byte) 0);
            }
            return out;
        } catch (java.security.GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    private static final SecureRandom RNG = new SecureRandom();

    /** Random bits from SecureRandom (the web app uses crypto.getRandomValues). */
    public static byte[] randomBits(int n) {
        byte[] b = new byte[(n + 7) / 8];
        RNG.nextBytes(b);
        byte[] bits = Arrays.copyOf(bytesToBits(b), n);
        Arrays.fill(b, (byte) 0);
        return bits;
    }
